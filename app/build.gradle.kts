/**
 * Release signing is opt-in.
 *
 * The keystore must never be committed. Create `keystore.properties` at the
 * repository root with storeFile / storePassword / keyAlias / keyPassword, and
 * back the .jks up somewhere safe - losing it means the app can never be
 * updated on Play under the same identity. Without the file the release build
 * is signed with the debug key, so `assembleRelease` still works for testing
 * (and installs over the existing debug build without wiping app data).
 */
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        FileInputStream(keystorePropsFile).use { load(it) }
    }
}
val hasReleaseKeystore = keystorePropsFile.exists()

